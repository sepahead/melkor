function updateLoadProgress(event) {
  if (event && event.lengthComputable && event.total) {
    const progress = Math.min(100, (event.loaded / event.total) * 100);
    const rounded = progress.toFixed(0);
    track.value = progress;
    pct.textContent = rounded + "%";
    track.setAttribute("aria-valuenow", progress.toFixed(1));
    track.setAttribute("aria-valuetext", rounded + " percent");
  } else if (event && event.loaded) {
    const loaded = formatBytes(event.loaded);
    pct.textContent = loaded;
    track.removeAttribute("aria-valuenow");
    track.setAttribute("aria-valuetext", loaded + " loaded");
  }
}

