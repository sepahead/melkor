// Packed scenes can have invalid Spark bounds. Use bounded center samples instead.
// Keep the more opaque half. Then use median coordinates and a percentile radius.
function computeBounds(mesh) {
  const maxSamples = 100_000;
  const knownCount = splatCountOf(mesh);
  const declaredCount = Number.isSafeInteger(knownCount) && knownCount > 0 ? knownCount : 0;
  const capacity = Math.min(declaredCount || maxSamples, maxSamples);
  const xs = new Float64Array(capacity);
  const ys = new Float64Array(capacity);
  const zs = new Float64Array(capacity);
  const opacities = new Float64Array(capacity);
  let sampleCount = 0;

  const addSample = (c, opacity) => {
    if (!Number.isFinite(c.x) || !Number.isFinite(c.y) || !Number.isFinite(c.z)) return;
    if (sampleCount >= capacity) return;
    xs[sampleCount] = c.x;
    ys[sampleCount] = c.y;
    zs[sampleCount] = c.z;
    opacities[sampleCount] = Number.isFinite(opacity) ? opacity : 1;
    sampleCount++;
  };

  // PackedSplats exposes indexed reads. Sample its full index range without
  // decoding every splat on the UI thread.
  if (declaredCount > 0 && typeof mesh?.splats?.getSplat === "function") {
    for (let sample = 0; sample < capacity; sample++) {
      const index = capacity === 1
        ? 0
        : Math.floor(sample * (declaredCount - 1) / (capacity - 1));
      const splat = mesh.splats.getSplat(index);
      addSample(splat.center, splat.opacity);
    }
  } else {
    // Keep the fallback bounded for alternate Spark splat sources.
    const stop = {};
    let visited = 0;
    try {
      mesh.forEachSplat((_i, c, _s, _q, opacity) => {
        if (visited++ >= capacity) throw stop;
        addSample(c, opacity);
      });
    } catch (error) {
      if (error !== stop) throw error;
    }
  }
  if (sampleCount === 0) return null;

  const scratch = new Float64Array(sampleCount);
  scratch.set(opacities.subarray(0, sampleCount));
  scratch.sort();
  const opacityThreshold = scratch[sampleCount >> 1];
  let solidCount = 0;
  for (let index = 0; index < sampleCount; index++) {
    if (opacities[index] >= opacityThreshold) solidCount++;
  }
  const useAll = solidCount < 64;
  if (useAll) solidCount = sampleCount;

  const median = (values) => {
    let output = 0;
    for (let index = 0; index < sampleCount; index++) {
      if (useAll || opacities[index] >= opacityThreshold) scratch[output++] = values[index];
    }
    scratch.subarray(0, output).sort();
    return scratch[output >> 1];
  };
  const center = new THREE.Vector3(median(xs), median(ys), median(zs));
  let output = 0;
  for (let index = 0; index < sampleCount; index++) {
    if (!useAll && opacities[index] < opacityThreshold) continue;
    scratch[output++] = Math.hypot(
      xs[index] - center.x,
      ys[index] - center.y,
      zs[index] - center.z,
    );
  }
  scratch.subarray(0, output).sort();
  const radiusIndex = Math.min(output - 1, Math.floor(output * 0.9));
  const radius = scratch[radiusIndex];
  if (!Number.isFinite(radius)) return null;
  return {
    center,
    radius: Math.max(radius, 1e-3),
    count: declaredCount || sampleCount,
    solid: solidCount,
  };
}

function frameMesh(mesh) {
  let b = null;
  try {
    b = computeBounds(mesh);
  } catch (error) {
    console.warn("Could not compute scene bounds. The viewer will use the default camera.", error);
  }
  if (!b) { target.set(0, 0, 0); orbitRadius = 5; applyOrbit(); return; }
  // Bounds are in mesh-local space; apply the mesh world transform to the center.
  const center = b.center.clone().multiply(mesh.scale).applyQuaternion(mesh.quaternion).add(mesh.position);
  target.copy(center);
  const s = Math.max(mesh.scale.x, mesh.scale.y, mesh.scale.z);
  const r = Math.max(b.radius * s, 1e-3);
  const fov = THREE.MathUtils.degToRad(camera.fov);
  orbitRadius = (r / Math.sin(fov / 2)) * 1.35;
  camera.near = Math.max(orbitRadius / 1000, 0.01);
  camera.far = orbitRadius * 50;
  camera.updateProjectionMatrix();
  applyOrbit();
}

function applyOrbit() {
  const ce = Math.cos(orbitElevation), se = Math.sin(orbitElevation);
  const ca = Math.cos(orbitAzimuth), sa = Math.sin(orbitAzimuth);
  camera.position.set(
    target.x + orbitRadius * ce * ca,
    target.y + orbitRadius * se,
    target.z + orbitRadius * ce * sa,
  );
  camera.lookAt(target);
}

