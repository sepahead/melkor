async function readPackagedSceneIndex() {
  try {
    const response = await fetch("./public/scene-index.json");
    if (!response.ok) return null;
    const index = JSON.parse(await readBoundedUtf8(response, 64 * 1024));
    const knownIds = new Set(SCENES.map((sceneDef) => sceneDef.id));
    if (index?.version !== 1 || !Array.isArray(index.scenes) ||
        !index.scenes.every((id) => typeof id === "string" && knownIds.has(id)) ||
        new Set(index.scenes).size !== index.scenes.length) {
      throw new Error("invalid packaged scene index");
    }
    return new Set(index.scenes);
  } catch (error) {
    console.warn("Could not read the packaged scene index:", error);
    return null;
  }
}

// Use the packaged index when it exists. The development server falls back to
// HEAD probes because external fixtures are optional and remain outside packages.
(async () => {
  const packagedScenes = await readPackagedSceneIndex();
  let availableScenes;
  if (packagedScenes) {
    availableScenes = SCENES.filter((sceneDef) => packagedScenes.has(sceneDef.id));
  } else {
    const ok = await Promise.all(SCENES.map(async (s) => {
      const url = SPLAT_DIR + (s.temporal ? s.manifest : s.file);
      try { return (await fetch(url, { method: "HEAD" })).ok; } catch { return false; }
    }));
    availableScenes = SCENES.filter((_, index) => ok[index]);
  }
  SCENES.splice(0, SCENES.length, ...availableScenes);
  buildSceneButtons();
  state.ready = true;
  const requestedScene = new URLSearchParams(window.location.search).get("scene");
  const initialScene = SCENES.find((sceneDef) => sceneDef.id === requestedScene) ?? SCENES[0];
  if (initialScene) {
    loadScene(initialScene.id).catch((error) => console.error(error));
  } else {
    const message = "No bundled scene is available. Run the asset setup or open a local splat.";
    state.error = message;
    showError(message, () => openLocalFilePickerFromError(), "Open local splat");
  }
})();
