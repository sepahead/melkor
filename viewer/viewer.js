async function openLocalFile(file) {
  if (!renderAvailable) return null;
  const openGeneration = ++localOpenGen;
  ++loadGen;
  detachProgressiveMesh();
  state.loading = true;
  state.error = null;
  const overlayTicket = showOverlay("Checking local file…");
  let descriptor;
  try {
    descriptor = await validateLocalFile(file, LOCAL_FILE_TYPES);
  } catch (error) {
    if (openGeneration !== localOpenGen) return null;
    state.loading = false;
    showLocalFileError(error instanceof Error ? error.message : String(error));
    return null;
  }
  if (openGeneration !== localOpenGen) return null;
  if (overlayTicket !== overlayGeneration) {
    state.loading = false;
    return null;
  }

  const candidate = {
    id: "local-file",
    label: file.name,
    fmt: descriptor.fmt,
    note: `${formatBytes(file.size)} · local only`,
    localFile: file,
    fileType: descriptor.type,
  };
  pendingLocalSceneDef = candidate;
  return loadScene(candidate.id, candidate);
}

